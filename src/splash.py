PAINT_SECONDS = 0.2      # whole picture on screen within this
HOLD_SECONDS = 0.1       # then leave it up this long before wiping
VT_PROCESSING = 0x0004


def _enable_ansi():
    """Turn on escape-sequence handling for this console, if it needs it."""
    if os.name != 'nt':
        return True
    try:
        import ctypes
        kernel32 = ctypes.windll.kernel32
        handle = kernel32.GetStdHandle(-11)          # STD_OUTPUT_HANDLE
        mode = ctypes.c_ulong()
        if not kernel32.GetConsoleMode(handle, ctypes.byref(mode)):
            return False
        return bool(kernel32.SetConsoleMode(handle, mode.value | VT_PROCESSING))
    except Exception:
        return False


def clear(ansi):
    if ansi:
        sys.stdout.write('\033[2J\033[H')            # wipe, cursor home
        sys.stdout.flush()
    elif os.name == 'nt':
        os.system('cls')
    else:
        os.system('clear')


def show(force=False):
    """No-op unless we are painting to a real console wide enough to hold it."""
    lines = ART.splitlines()
    if not force:
        try:
            if not sys.stdout.isatty():
                return False
        except (AttributeError, ValueError):
            return False
        if shutil.get_terminal_size((0, 0)).columns < max(len(l) for l in lines):
            return False

    ansi = _enable_ansi()
    step = PAINT_SECONDS / len(lines)
    for line in lines:
        sys.stdout.write(line + '\n')
        sys.stdout.flush()
        time.sleep(step)
    time.sleep(HOLD_SECONDS)
    clear(ansi)
    return True
