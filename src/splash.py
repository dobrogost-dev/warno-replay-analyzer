ARTS = (ART_ONE, ART_TWO, ART_THREE)

PAINT_SECONDS = 0.2      # whole picture on screen within this
HOLD_SECONDS = 0.1       # then leave it up this long before wiping
VT_PROCESSING = 0x0004


def _enable_ansi():
    """Turn on escape-sequence handling for this console, if it needs it."""
    if os.name != 'nt':
        return True
    try:
        import ctypes
        kernel32 = ctypes.windll.kernel32
        handle = kernel32.GetStdHandle(-11)          # STD_OUTPUT_HANDLE
        mode = ctypes.c_ulong()
        if not kernel32.GetConsoleMode(handle, ctypes.byref(mode)):
            return False
        return bool(kernel32.SetConsoleMode(handle, mode.value | VT_PROCESSING))
    except Exception:
        return False


def _clear_win32():
    """Blank the whole screen buffer through the console API.

    ESC[2J is not enough on Windows: conhost implements it by scrolling the
    buffer, so the art is still sitting right above the new output. Overwriting
    every cell is the only wipe that actually removes it.
    """
    try:
        import ctypes
        from ctypes import wintypes

        class CONSOLE_SCREEN_BUFFER_INFO(ctypes.Structure):
            _fields_ = [('dwSize', wintypes._COORD),
                        ('dwCursorPosition', wintypes._COORD),
                        ('wAttributes', wintypes.WORD),
                        ('srWindow', wintypes.SMALL_RECT),
                        ('dwMaximumWindowSize', wintypes._COORD)]

        kernel32 = ctypes.windll.kernel32
        handle = kernel32.GetStdHandle(-11)
        info = CONSOLE_SCREEN_BUFFER_INFO()
        if not kernel32.GetConsoleScreenBufferInfo(handle, ctypes.byref(info)):
            return False

        origin = wintypes._COORD(0, 0)
        cells = info.dwSize.X * info.dwSize.Y
        written = wintypes.DWORD()
        kernel32.FillConsoleOutputCharacterW(handle, ctypes.c_wchar(' '), cells,
                                             origin, ctypes.byref(written))
        kernel32.FillConsoleOutputAttribute(handle, info.wAttributes, cells,
                                            origin, ctypes.byref(written))
        kernel32.SetConsoleCursorPosition(handle, origin)
        return True
    except Exception:
        return False


def clear(ansi):
    if os.name == 'nt' and _clear_win32():
        return
    if ansi:
        # 3J drops the scrollback too, so nothing is left to scroll back up to
        sys.stdout.write('\033[2J\033[3J\033[H')
        sys.stdout.flush()
        return
    os.system('cls' if os.name == 'nt' else 'clear')


def _fits(art, size):
    lines = art.splitlines()
    # one row spare for the cursor, otherwise the top scrolls off mid-paint
    return (max(len(l) for l in lines) <= size.columns
            and len(lines) <= size.lines - 1)


def show(force=False, art=None):
    """Paint a picture the console can actually hold, then wipe it.

    Pictures taller than the window would scroll their own top away while being
    drawn, so the choice is made among the ones that fit here and now.
    """
    if art is not None:
        lines = art.splitlines()
    elif force:
        lines = random.choice(ARTS).splitlines()
    else:
        try:
            if not sys.stdout.isatty():
                return False
        except (AttributeError, ValueError):
            return False
        size = shutil.get_terminal_size((0, 0))
        candidates = [a for a in ARTS if _fits(a, size)]
        if not candidates:
            return False
        lines = random.choice(candidates).splitlines()

    ansi = _enable_ansi()
    step = PAINT_SECONDS / len(lines)
    for i, line in enumerate(lines):
        try:
            sys.stdout.write(line + '\n')
            sys.stdout.flush()
        except (UnicodeEncodeError, OSError):
            # console cannot render the block characters -- back out cleanly
            if i:
                clear(ansi)
            return False
        time.sleep(step)
    time.sleep(HOLD_SECONDS)
    clear(ansi)
    return True
